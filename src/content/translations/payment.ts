export const paymentMessages: Record<AppLocale, PaymentMessages> = {
  'zh-TW': paymentZhTW,
  'zh-CN': paymentZhCN,
  en: paymentEn,
};

export function buildPaymentT(locale: AppLocale) {
  const messages = paymentMessages[locale];
  return {
    ...messages,
    format(key: keyof PaymentMessages, vars?: Record<string, string | number>) {
      return formatMessage(messages[key], vars);
    },
    paymentMethodLabel(method: PaymentMethodCode) {
      switch (method) {
        case 'card':
          return messages.methodCard;
        case 'fps':
          return messages.methodFps;
        case 'bank_transfer':
          return messages.methodBank;
        default:
          return method;
      }
    },
  };
}

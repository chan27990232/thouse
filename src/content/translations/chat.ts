export const chatMessages: Record<AppLocale, ChatMessages> = {
  'zh-TW': chatZhTW,
  'zh-CN': chatZhCN,
  en: chatEn,
};

export function buildChatT(locale: AppLocale) {
  const messages = chatMessages[locale];
  return {
    ...messages,
    format(key: keyof ChatMessages, vars?: Record<string, string | number>) {
      return formatMessage(messages[key], vars);
    },
  };
}

/** 通知／列表中的角色後備標籤 */
export function translateRoleFallback(label: string, locale: AppLocale): string {
  const t = chatMessages[locale];
  if (label === '租客' || label === '业主') return t.tenant;
  if (label === '業主') return t.landlord;
  return label;
}

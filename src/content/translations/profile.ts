export const profileMessages: Record<AppLocale, ProfileMessages> = {
  'zh-TW': profileZhTW,
  'zh-CN': profileZhCN,
  en: profileEn,
};

export function buildProfileT(locale: AppLocale) {
  const messages = profileMessages[locale];
  return {
    ...messages,
    format(key: keyof ProfileMessages, vars?: Record<string, string | number>) {
      return formatMessage(messages[key], vars);
    },
  };
}

/** DB 稱謂值 → 顯示標籤 */
export function salutationLabel(value: string, locale: AppLocale): string {
  const t = profileMessages[locale];
  if (value === '先生') return t.salutationMr;
  if (value === '女士') return t.salutationMs;
  if (value === '不便透露') return t.salutationPreferNot;
  return value;
}

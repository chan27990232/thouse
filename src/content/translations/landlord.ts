export function buildLandlordT(locale: AppLocale) {
  const messages = landlordMessages[locale];
  return {
    ...messages,
    format(key: keyof LandlordMessages, vars?: Record<string, string | number>) {
      return formatMessage(messages[key], vars);
    },
  };
}
